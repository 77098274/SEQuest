
function escapeHtml(value) {
  return String(value ?? "Not available").replace(
    /[&<>"']/g,
    (char) =>
      ({
        "&": "&amp;",
        "<": "&lt;",
        ">": "&gt;",
        '"': "&quot;",
        "'": "&#39;",
      })[char]
  );
}

function PdfReportButton({
  user,
  sessionId,
  result,
  overallScore,
  performance,
  metrics,
  feedback,
  aiAnalysis,
  recommendations,
}) {
  const downloadReport = () => {
    const reportWindow = window.open("", "_blank");

    if (!reportWindow) {
      alert("Please allow pop-ups to generate your PDF report.");
      return;
    }

    const metricRows = metrics
      .map(
        (metric) => `
          <tr>
            <td>${escapeHtml(metric.label)}</td>
            <td>${metric.score}/100</td>
          </tr>
        `
      )
      .join("");

    const recommendationList = recommendations.length
      ? recommendations
          .map(
            (item) =>
              `<li>${escapeHtml(item)}</li>`
          )
          .join("")
      : "<li>No recommendations available.</li>";

    reportWindow.document.write(`
      <!DOCTYPE html>
      <html>
      <head>
        <title>SEQuest Project Report</title>
        <meta charset="UTF-8">
        <style>
          body {
            font-family: Arial, sans-serif;
            color: #1e293b;
            max-width: 800px;
            margin: 40px auto;
            padding: 24px;
            line-height: 1.6;
          }
          h1 { color: #4338ca; margin-bottom: 4px; }
          h2 {
            color: #3730a3;
            border-bottom: 1px solid #ddd;
            padding-bottom: 6px;
            margin-top: 28px;
          }
          .subtitle { color: #64748b; }
          .score {
            font-size: 38px;
            font-weight: bold;
            color: #4338ca;
          }
          .rating {
            display: inline-block;
            padding: 5px 12px;
            background: #eef2ff;
            border-radius: 6px;
            font-weight: bold;
          }
          table {
            width: 100%;
            border-collapse: collapse;
            margin-top: 12px;
          }
          th, td {
            padding: 11px;
            text-align: left;
            border-bottom: 1px solid #e2e8f0;
          }
          th { background: #f1f5f9; }
          li { margin-bottom: 8px; }
          .footer {
            margin-top: 36px;
            color: #64748b;
            font-size: 12px;
          }
          @media print {
            body { margin: 0; padding: 10px; }
          }
        </style>
      </head>
      <body>
        <h1>SEQuest</h1>
        <div class="subtitle">Software Project Management Simulation</div>

        <h2>Project Results</h2>
        <p><strong>Student:</strong> ${escapeHtml(user?.name)}</p>
        <p><strong>Session ID:</strong> ${escapeHtml(sessionId)}</p>
        <p><strong>Report date:</strong> ${escapeHtml(new Date().toLocaleDateString())}</p>

        <p>Overall Project Score</p>
        <div class="score">${overallScore}/100</div>
        <p class="rating">${escapeHtml(performance.rating)}</p>
        <p>${escapeHtml(performance.description)}</p>

        <h2>Performance Breakdown</h2>
        <table>
          <thead>
            <tr><th>Metric</th><th>Score</th></tr>
          </thead>
          <tbody>${metricRows}</tbody>
        </table>

        <h2>Personalized Feedback</h2>
        <p><strong>Area to improve:</strong>
          ${escapeHtml(feedback.weakest.label)}
          (${feedback.weakest.score}/100)
        </p>
        <p><strong>Suggestion:</strong>
          ${escapeHtml(feedback.suggestion)}
        </p>

        <h2>AI Risk Assessment</h2>
        <p><strong>Risk Level:</strong>
          ${escapeHtml(aiAnalysis?.risk_level)}
        </p>
        <p><strong>Predicted Risk:</strong>
          ${escapeHtml(aiAnalysis?.predicted_risk)}
        </p>

        <h2>AI Recommendations</h2>
        <ul>${recommendationList}</ul>

        <div class="footer">
          Generated by SEQuest. Scores reflect this simulation's recorded results.
        </div>
      </body>
      </html>
    `);

    reportWindow.document.close();
    reportWindow.focus();

    reportWindow.onload = () => {
      reportWindow.print();
    };
  };

  return (
    <button
      type="button"
      className="primary-button"
      onClick={downloadReport}
    >
      ↓ Download PDF Report
    </button>
  );
}

export default PdfReportButton;
